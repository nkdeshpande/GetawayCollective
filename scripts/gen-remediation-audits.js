#!/usr/bin/env node
/**
 * REMEDIATION AUDIT GENERATOR — the inventories, derived not written
 *
 * Writes docs/remediation/ from the registries and the source tree.
 * Everything under that directory except classifications is GENERATED:
 * an inventory typed by hand is stale by the second commit, and a stale
 * inventory sends the next agent to lines that moved.
 *
 * The canon lives in constants/ — public-laws.ts, remediation.ts,
 * route-contracts.ts. This produces the evidence views the Day 01 brief
 * asks for, pointed at that canon rather than restating it.
 *
 * Run:  npm run remediation:audits
 */

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "docs", "remediation");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8").replace(/\r\n/g, "\n");
const strip = (s) => s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

fs.mkdirSync(path.join(OUT, "audits"), { recursive: true });
fs.mkdirSync(path.join(OUT, "registry"), { recursive: true });

const STAMP =
  "<!-- GENERATED by scripts/gen-remediation-audits.js — do not edit. " +
  "Canon lives in constants/public-laws.ts, constants/remediation.ts, constants/route-contracts.ts. -->\n\n";

/* ── README: the pointer, not a fork ─────────────────────────────── */
fs.writeFileSync(path.join(OUT, "README.md"), STAMP + `# Remediation program

The laws, the registry and the route contracts are CODE, not documents:

| Canon | File | Enforced by |
|---|---|---|
| Public UX laws | \`constants/public-laws.ts\` | \`scripts/public-law-lint.js\` (verify chain) |
| Remediation registry | \`constants/remediation.ts\` | same lint: integrity, ratchet, status honesty |
| Route contracts | \`constants/route-contracts.ts\` | \`tests/remediation.test.ts\` |

Everything in this directory is generated evidence. Do not edit it, and do
not cite it as authority — regenerate it with \`npm run remediation:audits\`.

The audit prose of 4 Aug 2026 is EVIDENCE about a moment. The laws are the
canon. An agent resolving an item reads the law, never the paragraph.

## Severity contract

- **P0** — material trust, legal or financial meaning, or a broken primary
  public action. Blocks release.
- **P1** — major comprehension, navigation, accessibility or mobile
  architecture. Blocks release unless waived in the registry with owner
  and revisit date.
- **P2** — hierarchy, density, consistency. Ships only with an owner.
- **P3** — polish. Never blocks.

## Agent rules

Before touching any remediation item, read the rules in AGENTS.md
(§ Remediation). Shortest form: read the item, read its laws, inspect its
sources, never invent a state, a figure basis or a legal claim — those are
NEEDS_HUMAN_CANON, which is a status, not a failure.
`);

/* ── Ontology audit ───────────────────────────────────────────────── */
const SURFACES = [
  "app/_assemblies/atoms.tsx", "app/_assemblies/shell.tsx", "app/_assemblies/gateway.tsx",
  "app/_assemblies/gatewaypages.tsx", "app/_assemblies/publicpages.tsx",
  "app/_assemblies/systempages.tsx", "app/_assemblies/documents.tsx",
  "app/_assemblies/property.tsx", "app/_system/surface.tsx",
];
const LEAK = /\bvantage\b|GC-\d{3}|AS-\d{2}\b/;

let onto = STAMP + "# Public ontology occurrences\n\n" +
  "Every identifier or filing word a public surface ships, after comment\n" +
  "stripping. Classification is HUMAN work (REM-016): fill the column in\n" +
  "constants/remediation.ts follow-ups, not here — this file is regenerated.\n\n" +
  "| File | Line | Occurrence | Classification |\n|---|---|---|---|\n";
let ontoCount = 0;
for (const f of SURFACES) {
  strip(read(f)).split("\n").forEach((line, i) => {
    if (LEAK.test(line)) {
      ontoCount += 1;
      const snippet = line.trim().slice(0, 90).replace(/\|/g, "\\|");
      onto += `| ${f} | ${i + 1} | \`${snippet}\` | UNCLASSIFIED |\n`;
    }
  });
}
onto += `\nTotal lines carrying ontology: ${ontoCount}. The lint ratchets the term count; this lists where.\n`;
fs.writeFileSync(path.join(OUT, "audits", "public-ontology.md"), onto);

/* ── Financial figure audit ───────────────────────────────────────── */
const dataSrc = read("app/_assemblies/data.ts");
const vehiclesSrc = read("constants/vehicles.ts");
const yields = [...vehiclesSrc.matchAll(/key:\s*"(\w+)"[\s\S]*?toPartners:\s*(\d+|null)/g)]
  .map((m) => ({ key: m[1], toPartners: m[2] }));

let fin = STAMP + "# Public financial figures\n\n" +
  "| Route | Figure | Source | Class | Basis travels with it? |\n|---|---|---|---|---|\n";
for (const y of yields) {
  const derived = y.toPartners !== "null";
  fin += `| /collection · /collection/[vehicle] | ${y.key} yield | folded: toPartners/totalEquity ` +
    `(app/_assemblies/data.ts yieldOf) | ${derived ? "FORECAST" : "UNKNOWN (waterfall incomplete)"} | ` +
    `NO — REM-003 |\n`;
}
fin += `| /collection/[vehicle] | unit price, project total | constants/vehicles.ts via publishable() gate | actual (stated) | gate withholds when conflicted |\n`;
fin += `| /api/brochure/[vehicle] | same set | same registries | same | same gate |\n`;
fin += `\nNo hardcoded public yield was found: the class discipline exists (${/FORECAST/.test(dataSrc) ? "FORECAST verified in data.ts" : "NOT VERIFIED"}); the missing half is the basis (REM-003, NEEDS_HUMAN_CANON).\n`;
fs.writeFileSync(path.join(OUT, "audits", "financial-figures.md"), fin);

/* ── Asset & vehicle state audit ──────────────────────────────────── */
const states = [...vehiclesSrc.matchAll(
  /key:\s*"(\w+)"[\s\S]*?lifecycle:\s*"(\w+)"[\s\S]*?landArea:\s*"([^"]+)"[\s\S]*?propertyLifecycle:\s*"(\w+)"/g,
)].map((m) => ({ key: m[1], vehicle: m[2], land: m[3], property: m[4] }));

let st = STAMP + "# Asset and vehicle states\n\n" +
  "| Vehicle | Vehicle lifecycle | Property lifecycle | Land as stated | Rendered alias | Contradiction |\n|---|---|---|---|---|---|\n";
for (const s of states) {
  const alias = s.property === "acquired" ? "\"Land acquired\" (property.tsx hero)" :
    s.property === "development" ? "\"In development\"" : "\"Stabilised\"";
  const contra = s.key === "coorgcreek"
    ? "YES — record states possession, title unverified; alias implies settled title. REM-002."
    : "none found";
  st += `| ${s.key} | ${s.vehicle} | ${s.property} | ${s.land.replace(/\|/g, "\\|")} | ${alias} | ${contra} |\n`;
}
st += "\nCanonical mapping is NEEDS_HUMAN_CANON (REM-002): the lifecycle vocabulary is a legal decision.\n";
fs.writeFileSync(path.join(OUT, "audits", "asset-states.md"), st);

/* ── Media state audit ────────────────────────────────────────────── */
const pageSrc = read("constants/property-page.ts");
const slots = [...pageSrc.matchAll(/slot\("(\w+)\./g)].map((m) => m[1]);
const perEstate = {};
for (const s of slots) perEstate[s] = (perEstate[s] || 0) + 1;

let med = STAMP + "# Media states\n\n| Page | Declared slots | Assets registered | Public behaviour today |\n|---|---|---|---|\n";
for (const [k, n] of Object.entries(perEstate)) {
  med += `| ${k} | ${n} | ${(pageSrc.match(new RegExp(`${k}\\.[\\w]+"[^}]*asset:\\s*"`, "g")) || []).length} | one labelled placeholder PER SLOT — REM-008 |\n`;
}
med += "\nTarget state (PUBLIC.08): produced frames only, plus at most one consolidated disclosure; the slot list stays with the office as the commission brief.\n";
fs.writeFileSync(path.join(OUT, "audits", "media-states.md"), med);

/* ── Registry JSON export ─────────────────────────────────────────── */
const regSrc = read("constants/remediation.ts");
const items = regSrc.split(/\n  R\(\{/).slice(1).map((b) => ({
  id: (b.match(/id:\s*"(REM-\d+)"/) || [])[1],
  title: (b.match(/title:\s*\n?\s*"([^"]+)"/) || [])[1] ?? null,
  severity: (b.match(/severity:\s*"(P\d)"/) || [])[1],
  status: (b.match(/status:\s*"([A-Z_]+)"/) || [])[1],
  laws: [...new Set([...b.matchAll(/"(PUBLIC\.\d{2})"/g)].map((m) => m[1]))],
}));
fs.writeFileSync(
  path.join(OUT, "registry", "remediation.json"),
  JSON.stringify({
    generated: "by scripts/gen-remediation-audits.js — canonical source is constants/remediation.ts",
    items,
  }, null, 2),
);

console.log(
  `[remediation-audits] wrote docs/remediation — ${ontoCount} ontology lines · ` +
  `${yields.length} yield figures · ${states.length} vehicles · ${Object.keys(perEstate).length} media pages · ` +
  `${items.length} registry items exported`,
);
